    select 1 from public.piquins_administradores a
    where a.usuario_id = (select auth.uid())
  )
);

create policy "PIQUINS admin reemplaza fotos"
on storage.objects for update to authenticated
using (
  bucket_id = 'piquins-productos'
  and exists (
    select 1 from public.piquins_administradores a
    where a.usuario_id = (select auth.uid())
  )
)
with check (
  bucket_id = 'piquins-productos'
  and name like 'catalogo/%'
  and exists (
    select 1 from public.piquins_administradores a
    where a.usuario_id = (select auth.uid())
  )
);

create policy "PIQUINS admin elimina fotos"
on storage.objects for delete to authenticated
using (
  bucket_id = 'piquins-productos'
  and exists (
    select 1 from public.piquins_administradores a
    where a.usuario_id = (select auth.uid())
  )
);

-- Comprobación: ambas tablas de PIQUINS deben devolver rowsecurity = true.
select schemaname, tablename, rowsecurity
from pg_tables
where schemaname = 'public'
  and tablename in ('piquins_administradores','piquins_productos')
order by tablename;

