create table public.piquins_administradores (
  usuario_id uuid primary key references auth.users(id) on delete cascade
);

create table public.piquins_productos (
  id bigint generated by default as identity primary key,
  codigo text unique,
  nombre text not null check (length(btrim(nombre)) > 0),
  descripcion text,
  categoria text not null default 'Productos',
  precio numeric(12,2) check (precio is null or precio >= 0),
  imagen text,
  video text,
  destacado boolean not null default false,
  activo boolean not null default false,
  creado_en timestamptz not null default now()
);

alter table public.piquins_administradores enable row level security;
alter table public.piquins_productos enable row level security;

grant usage on schema public to anon, authenticated;
grant select on public.piquins_administradores to authenticated;
grant select on public.piquins_productos to anon, authenticated;
grant insert, update, delete on public.piquins_productos to authenticated;

create policy "PIQUINS admin consulta su permiso"
on public.piquins_administradores for select to authenticated
using (usuario_id = (select auth.uid()));

create policy "PIQUINS publico ve activos"
on public.piquins_productos for select to anon, authenticated
using (activo = true);

create policy "PIQUINS admin ve inventario"
on public.piquins_productos for select to authenticated
using (
  exists (
    select 1 from public.piquins_administradores a
    where a.usuario_id = (select auth.uid())
  )
);

create policy "PIQUINS admin crea productos"
on public.piquins_productos for insert to authenticated
with check (
  exists (
    select 1 from public.piquins_administradores a
    where a.usuario_id = (select auth.uid())
  )
);

create policy "PIQUINS admin edita productos"
on public.piquins_productos for update to authenticated
using (
  exists (
    select 1 from public.piquins_administradores a
    where a.usuario_id = (select auth.uid())
  )
)
with check (
  exists (
    select 1 from public.piquins_administradores a
    where a.usuario_id = (select auth.uid())
  )
);

create policy "PIQUINS admin elimina productos ocultos"
on public.piquins_productos for delete to authenticated
using (
  activo = false
  and exists (
    select 1 from public.piquins_administradores a
    where a.usuario_id = (select auth.uid())
  )
);

-- Las fotos nuevas se subirán aquí. Las originales permanecen en GitHub.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('piquins-productos', 'piquins-productos', true, 5242880,
        array['image/jpeg','image/png','image/webp'])
on conflict (id) do nothing;

create policy "PIQUINS admin consulta fotos"
on storage.objects for select to authenticated
using (
  bucket_id = 'piquins-productos'
  and exists (
    select 1 from public.piquins_administradores a
    where a.usuario_id = (select auth.uid())
  )
